/** 引号 / 书名号里的原话不改（素材名、用户的为什么） */
function protect(s: string): { text: string; back: (t: string) => string } {
  const keep: string[] = [];
  const text = s.replace(/《[^》]*》|「[^」]*」|“[^”]*”/g, (m) => {
    keep.push(m);
    return `\u0000${keep.length - 1}\u0000`;
  });
  return { text, back: (t) => t.replace(/\u0000(\d+)\u0000/g, (_m, i) => keep[Number(i)]) };
}

/** 改写一段文字，返回新文字和命中的规则 id */
export function deai(s: string | undefined): { text: string; hits: string[] } {
  if (!s) return { text: s || '', hits: [] };
  const p = protect(s);
  let t = p.text;
  const hits: string[] = [];
  for (const r of DEAI_RULES) {
    r.re.lastIndex = 0;
    if (!r.re.test(t)) continue;
    r.re.lastIndex = 0;
    t = t.replace(r.re, r.to as never);
    hits.push(r.id);
  }
  if (hits.length) t = t.replace(/，，+/g, '，').replace(/^[，、\s]+/, '').replace(/([。！？])[，、]+/g, '$1').replace(/\s{2,}/g, ' ').trim();
  return { text: p.back(t), hits };
}

/** 新枝的几段字都过一遍；deai = 改了几处 */
export function deaiIdea<T extends { title: string; idea: string; bridge: string; unlike?: string; experiment?: string; deai?: number }>(b: T): T {
  let n = 0;
  const fix = (x: string | undefined) => {
    if (!x) return x;
    const r = deai(x);
    n += r.hits.length;
    return r.text || x;
  };
  const out = { ...b, title: fix(b.title)!, idea: fix(b.idea)!, bridge: fix(b.bridge)!, unlike: fix(b.unlike), experiment: fix(b.experiment) };
  if (n) out.deai = n;
  return out;
}
